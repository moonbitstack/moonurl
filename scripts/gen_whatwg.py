#!/usr/bin/env python3
"""Generate the URL and host name conformance tests from web-platform-tests.

Sources:
  * url/resources/urltestdata.json   -- what a string parses to, and against
                                        what base
  * url/resources/setters_tests.json -- what each setter does to a URL
  * url/resources/toascii.json       -- host names, through domain to ASCII

Writes src/vectors_url_test.mbt and src/vectors_host_test.mbt.  Run from the
repository root.  Nothing here ships with the library.
"""

import json
import os
import subprocess
import sys
import urllib.request

WPT = "https://raw.githubusercontent.com/web-platform-tests/wpt/master/url/resources/"
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")
UNCHECKED = "\u0001"


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        sys.stderr.write("fetching %s\n" % (WPT + name))
        with urllib.request.urlopen(WPT + name) as response:
            open(path, "wb").write(response.read())
    return json.loads(open(path, encoding="utf-8").read())


def literal(text):
    out = []
    for character in text:
        point = ord(character)
        if character == '"':
            out.append('\\"')
        elif character == "\\":
            out.append("\\\\")
        elif 0x20 <= point < 0x7F:
            out.append(character)
        else:
            out.append("\\u{%X}" % point)
    return '"' + "".join(out) + '"'


def lone_surrogate(text):
    return any(0xD800 <= ord(character) <= 0xDFFF for character in text)


def plain(text):
    """A JSON string as a MoonBit literal, lone surrogates read as U+FFFD.

    A MoonBit string cannot hold an unpaired surrogate, and the standard's
    input is a scalar value string: a surrogate is not one, and stands for the
    replacement character.
    """
    out = []
    for character in text:
        if 0xD800 <= ord(character) <= 0xDFFF:
            out.append("\uFFFD")
        else:
            out.append(character)
    return "".join(out)


FIELDS = [
    "protocol",
    "username",
    "password",
    "host",
    "hostname",
    "port",
    "pathname",
    "search",
    "hash",
    "origin",
]


def url_cases():
    cases = []
    for entry in fetch("urltestdata.json"):
        if not isinstance(entry, dict) or "relativeTo" in entry:
            continue
        base = plain(entry["base"] or "")
        source = plain(entry["input"])
        if entry.get("failure"):
            cases.append((True, source, base, [""] * len(FIELDS), ""))
            continue
        fields = [plain(entry[key]) for key in FIELDS if key != "origin"]
        origin = plain(entry["origin"]) if "origin" in entry else UNCHECKED
        fields = (
            [
                plain(entry["protocol"]),
                plain(entry["username"]),
                plain(entry["password"]),
                plain(entry["host"]),
                plain(entry["hostname"]),
                plain(entry["port"]),
                plain(entry["pathname"]),
                plain(entry["search"]),
                plain(entry["hash"]),
                origin,
            ]
        )
        cases.append((False, source, base, fields, plain(entry["href"])))
    return cases


SETTERS = [
    "protocol",
    "username",
    "password",
    "host",
    "hostname",
    "port",
    "pathname",
    "search",
    "hash",
    "href",
]


def setter_cases():
    cases = []
    for member in SETTERS:
        for entry in fetch("setters_tests.json").get(member, []):
            if not isinstance(entry, dict):
                continue
            expected = entry["expected"]
            fields = [
                plain(str(expected[key])) if key in expected else UNCHECKED
                for key in SETTERS
            ]
            cases.append(
                (member, plain(entry["href"]), plain(entry["new_value"]), fields)
            )
    return cases


def emit_url_tests(cases, setters):
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_whatwg.py from web-platform-tests",
        "// urltestdata.json and setters_tests.json. Do not edit.",
        "",
        "///|",
        "/// One row of urltestdata.json: whether parsing fails, the input and the",
        "/// base it is read against, then what each getter should say and the",
        "/// serialisation. An origin of `\\u{1}` is one the suite does not check.",
        "struct Case {",
        "  failure : Bool",
        "  input : String",
        "  base : String",
        "  href : String",
        "  protocol : String",
        "  username : String",
        "  password : String",
        "  host : String",
        "  hostname : String",
        "  port : String",
        "  pathname : String",
        "  search : String",
        "  hash : String",
        "  origin : String",
        "}",
        "",
        "///|",
        "let url_cases : Array[Case] = [",
    ]
    for failure, source, base, fields, href in cases:
        lines.append(
            "  { failure: %s, input: %s, base: %s, href: %s, protocol: %s, "
            "username: %s, password: %s, host: %s, hostname: %s, port: %s, "
            "pathname: %s, search: %s, hash: %s, origin: %s },"
            % (
                "true" if failure else "false",
                literal(source),
                literal(base),
                literal(href),
                literal(fields[0]),
                literal(fields[1]),
                literal(fields[2]),
                literal(fields[3]),
                literal(fields[4]),
                literal(fields[5]),
                literal(fields[6]),
                literal(fields[7]),
                literal(fields[8]),
                literal(fields[9]),
            )
        )
    lines.append("]")
    lines.append("")
    lines.append('test "URL parsing from web-platform-tests" {')
    lines.append("  let complaints : Array[String] = []")
    lines.append("  for case in url_cases {")
    lines.append("    let base = if case.base == \"\" {")
    lines.append("      None")
    lines.append("    } else {")
    lines.append("      try {")
    lines.append("        Some(@moonurl.Url::decode(case.base[:], syntax=@moonurl.Whatwg))")
    lines.append("      } catch {")
    lines.append("        _ => None")
    lines.append("      }")
    lines.append("    }")
    lines.append("    let parsed = try {")
    lines.append(
        "      Some(@moonurl.Url::decode(case.input[:], syntax=@moonurl.Whatwg, base?=base))"
    )
    lines.append("    } catch {")
    lines.append("      _ => None")
    lines.append("    }")
    lines.append("    match parsed {")
    lines.append("      None =>")
    lines.append(
        '        note_flag(complaints, case.failure, case.input, "refusal", case.base)'
    )
    lines.append("      Some(url) => {")
    lines.append(
        '        note_flag(complaints, !case.failure, case.input, "acceptance", case.base)'
    )
    lines.append(
        '        note(complaints, url.encode() == case.href, case.input, "href", '
        "url.encode(), case.href)"
    )
    lines.append("        let fields = fields_of(url)")
    lines.append("        let want = [")
    lines.append("          case.protocol, case.username, case.password, case.host,")
    lines.append("          case.hostname, case.port, case.pathname, case.search, case.hash,")
    lines.append("          case.origin,")
    lines.append("        ]")
    lines.append('        let names = ["protocol", "username", "password", "host",')
    lines.append('          "hostname", "port", "pathname", "search", "hash", "origin"]')
    lines.append("        for i, name in names {")
    lines.append("          if want[i] != unchecked {")
    lines.append("            note(complaints, fields[i] == want[i], case.input, name, fields[i], want[i])")
    lines.append("          }")
    lines.append("        }")
    lines.append("      }")
    lines.append("    }")
    lines.append("  }")
    lines.append("  complain(complaints)")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("/// One row of setters_tests.json: which member is set, to what, on")
    lines.append("/// which URL, and what every getter should say afterwards. A getter")
    lines.append("/// the row does not mention is `\\u{1}`.")
    lines.append("struct Setting {")
    lines.append("  which : String")
    lines.append("  href : String")
    lines.append("  value : String")
    lines.append("}")
    lines.append("")
    lines.append("///|")
    lines.append("let setter_cases : Array[(Setting, Array[String])] = [")
    for member, href, value, fields in setters:
        lines.append(
            "  ({ which: %s, href: %s, value: %s }, [%s]),"
            % (
                literal(member),
                literal(href),
                literal(value),
                ", ".join(literal(field) for field in fields),
            )
        )
    lines.append("]")
    lines.append("")
    lines.append('test "URL setters from web-platform-tests" {')
    lines.append("  let complaints : Array[String] = []")
    lines.append('  let names = ["protocol", "username", "password", "host",')
    lines.append('    "hostname", "port", "pathname", "search", "hash", "href"]')
    lines.append("  for (setting, want) in setter_cases {")
    lines.append("    let url = @moonurl.Url::decode(setting.href[:], syntax=@moonurl.Whatwg)")
    lines.append("    let value = setting.value[:]")
    lines.append("    let got = match setting.which {")
    lines.append('      "protocol" => url.set_scheme(value)')
    lines.append('      "username" => url.set_username(value)')
    lines.append('      "password" => url.set_password(value)')
    lines.append('      "host" => url.set_host(value)')
    lines.append('      "hostname" => url.set_hostname(value)')
    lines.append('      "port" => url.set_port(value)')
    lines.append('      "pathname" => url.set_path(value)')
    lines.append('      "search" => url.set_query(value)')
    lines.append('      "hash" => url.set_fragment(value)')
    lines.append('      "href" => @moonurl.Url::decode(value, syntax=@moonurl.Whatwg)')
    lines.append('      _ => url')
    lines.append("    }")
    lines.append("    let fields = fields_of(got)")
    lines.append("    for i, name in names {")
    lines.append("      if want[i] != unchecked {")
    lines.append(
        "        let got = if i == 9 { got.encode() } else { fields[i] }"
    )
    lines.append(
        "        note(complaints, got == want[i], setting.href, name, got, want[i])"
    )
    lines.append("      }")
    lines.append("    }")
    lines.append("  }")
    lines.append("  complain(complaints)")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def emit_host_tests(cases):
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_whatwg.py from web-platform-tests",
        "// toascii.json. Do not edit.",
        "",
        "///|",
        "/// A host name and what the URL standard's domain to ASCII makes of it,",
        "/// or the empty string where it refuses it.",
        "let host_cases : Array[(String, String)] = [",
    ]
    for source, output in cases:
        lines.append("  (%s, %s)," % (literal(source), literal(output)))
    lines.append("]")
    lines.append("")
    lines.append('test "host names from web-platform-tests" {')
    lines.append("  let complaints : Array[String] = []")
    lines.append("  for (source, output) in host_cases {")
    lines.append("    let got = try {")
    lines.append("      @moonurl.domain(source[:])")
    lines.append("    } catch {")
    lines.append('      _ => ""')
    lines.append("    }")
    lines.append(
        '    note(complaints, got == output, source, "domain to ASCII", got, output)'
    )
    lines.append("  }")
    lines.append("  complain(complaints)")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def host_cases():
    cases = []
    for entry in fetch("toascii.json"):
        if not isinstance(entry, dict):
            continue
        source = plain(entry["input"])
        if lone_surrogate(entry["input"]):
            continue
        cases.append((source, plain(entry.get("output") or "")))
    return cases


def main():
    cases = url_cases()
    setters = setter_cases()
    open(
        os.path.join("src", "vectors_url_test.mbt"), "w", encoding="utf-8", newline="\n"
    ).write(emit_url_tests(cases, setters))
    hosts = host_cases()
    open(
        os.path.join("src", "vectors_host_test.mbt"), "w", encoding="utf-8", newline="\n"
    ).write(emit_host_tests(hosts))
    subprocess.run(["moon", "fmt"], check=False)
    sys.stderr.write("%d url cases, %d setter cases, %d host names\n" % (
        len(cases), len(setters), len(hosts)))


if __name__ == "__main__":
    main()
