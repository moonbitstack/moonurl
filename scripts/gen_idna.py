#!/usr/bin/env python3
"""Generate the IDNA tables and the UTS 46 conformance test.

Sources, all official:
  * IdnaMappingTable.txt  -- UTS 46 section 5, one status per code point
  * ArabicShaping.txt     -- Joining_Type, for the ContextJ rule of RFC 5892
  * IdnaTestV2.txt        -- the UTS 46 conformance suite

Writes src/idna/tables.mbt and src/idna/vectors_test.mbt.  Run from the
repository root.  Nothing here ships with the library.
"""

import os
import re
import subprocess
import sys
import urllib.request

UNICODE = "17.0.0"
IDNA = "https://www.unicode.org/Public/%s/idna/" % UNICODE
UCD = "https://www.unicode.org/Public/%s/ucd/" % UNICODE

VALID, IGNORED, MAPPED, DEVIATION, DISALLOWED = 0, 1, 2, 3, 4
STATUS_NAME = {
    "valid": VALID,
    "ignored": IGNORED,
    "mapped": MAPPED,
    "deviation": DEVIATION,
    "disallowed": DISALLOWED,
}
JOINING = {"U": 0, "R": 1, "L": 2, "D": 3, "C": 4, "T": 5}
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")


def fetch(name, base):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        sys.stderr.write("fetching %s\n" % (base + name))
        with urllib.request.urlopen(base + name) as response:
            open(path, "wb").write(response.read())
    return open(path, encoding="utf-8").read()


def records(text):
    """The data lines of a UCD file, comments stripped."""
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def span(field):
    if ".." in field:
        low, high = field.split("..")
    else:
        low = high = field
    return int(low, 16), int(high, 16)


def literal(text):
    """A MoonBit string literal for `text`, anything past ASCII escaped."""
    out = []
    for character in text:
        point = ord(character)
        if character == '"':
            out.append('\\"')
        elif character == "\\":
            out.append("\\\\")
        elif 0x20 <= point < 0x7F:
            out.append(character)
        else:
            out.append("\\u{%X}" % point)
    return '"' + "".join(out) + '"'


# ----------------------------------------------------------- the mapping table


def mapping_table():
    """(start, status with a mapping index) per run, plus the mapping strings."""
    runs = []
    maps = [""]
    index = {"": 0}
    for fields in records(fetch("IdnaMappingTable.txt", IDNA)):
        status = STATUS_NAME[fields[1]]
        low, _ = span(fields[0])
        target = ""
        if len(fields) > 2 and fields[2]:
            target = "".join(chr(int(point, 16)) for point in fields[2].split())
        if target not in index:
            index[target] = len(maps)
            maps.append(target)
        runs.append((low, status | (index[target] << 3)))
    return runs, maps


def joining_table():
    """(start, Joining_Type) for the code points ArabicShaping.txt names."""
    runs = []
    for fields in records(fetch("ArabicShaping.txt", UCD)):
        low, _ = span(fields[0])
        runs.append((low, JOINING[fields[2]]))
    runs.sort()
    # One entry per run start is enough: the type holds until the next one.
    return runs


def emit_tables(runs, maps, joining):
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_idna.py from the Unicode %s files" % UNICODE,
        "// IdnaMappingTable.txt and ArabicShaping.txt. Do not edit.",
        "",
        "///|",
        "/// One entry per run of code points that share a status and a mapping:",
        "/// the run's first code point, and the status with the index of the",
        "/// mapping string above it. Runs are contiguous and cover the whole code",
        "/// space, so a code point belongs to the last run that starts at or below",
        "/// it.",
        "let idna_range : Array[(Int, Int)] = [",
    ]
    for low, code in runs:
        lines.append("  (0x%04X, 0x%X)," % (low, code))
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// The strings `idna_range` indexes into. The first is empty: most runs")
    lines.append("/// map nowhere.")
    lines.append("let idna_map : Array[String] = [")
    for target in maps:
        lines.append("  %s," % literal(target))
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// Joining_Type from ArabicShaping.txt, for the code points that have one")
    lines.append("/// worth knowing: 1 R, 2 L, 3 D, 4 C, 5 T. Anything absent is 0, U.")
    lines.append("let joining_range : Array[(Int, Int)] = [")
    for low, kind in joining:
        lines.append("  (0x%04X, %d)," % (low, kind))
    lines.append("]")
    lines.append("")
    return "\n".join(lines)


# ------------------------------------------------------------- the test suite


def unescape(field):
    """Undo the \\uXXXX and \\x{XXXX} escapes the test file writes."""
    field = field.replace("\\\\", "\x00")
    field = re.sub(r"\\u([0-9A-Fa-f]{4})", lambda m: chr(int(m.group(1), 16)), field)
    field = re.sub(r"\\x\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), field)
    return field.replace("\x00", "\\")


def text(field):
    """A field as text, where a pair of quotes stands for the empty string."""
    if field == '""':
        return ""
    return unescape(field)


def failed(field):
    """Whether a status column records any error at all."""
    field = field.strip()
    return bool(field) and field != "[]"


def ill_formed(text):
    return any(0xD800 <= ord(character) <= 0xDFFF for character in text)


def idna_suite():
    cases = []
    for fields in records(fetch("IdnaTestV2.txt", IDNA)):
        while len(fields) < 7:
            fields.append("")
        source = text(fields[0])
        unicode = text(fields[1]) if fields[1] else source
        ascii_n = text(fields[3]) if fields[3] else unicode
        ascii_t = text(fields[5]) if fields[5] else ascii_n
        unicode_status = failed(fields[2])
        ascii_n_status = failed(fields[4]) if fields[4] else unicode_status
        ascii_t_status = failed(fields[6]) if fields[6] else ascii_n_status
        if ill_formed(source) or ill_formed(unicode):
            continue
        cases.append(
            (
                source,
                unicode,
                unicode_status,
                ascii_n,
                ascii_n_status,
                ascii_t,
                ascii_t_status,
            )
        )
    return cases


def emit_idna_tests(cases):
    """One array of rows per batch, so that no stretch of the file is a single
    endless literal, and one test that walks them all."""
    chunk = 800
    batches = [cases[i : i + chunk] for i in range(0, len(cases), chunk)]
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_idna.py from IdnaTestV2.txt of the same",
        "// Unicode version. Do not edit.",
        "",
        "// A row is the source, then for each of toUnicode, toASCII",
        "// nontransitional and toASCII transitional the name the standard expects",
        "// and whether it records an error for it. Rows whose source holds an",
        "// unpaired surrogate are left out: a MoonBit string cannot hold one.",
        "",
    ]
    for number, batch in enumerate(batches):
        lines.append("///|")
        lines.append("let uts46_%d : Array[(String, String, Bool, String, Bool, String, Bool)] = [" % number)
        for source, unicode, ubad, ascii_n, nbad, ascii_t, tbad in batch:
            lines.append(
                "  (%s, %s, %s, %s, %s, %s, %s),"
                % (
                    literal(source),
                    literal(unicode),
                    "true" if ubad else "false",
                    literal(ascii_n),
                    "true" if nbad else "false",
                    literal(ascii_t),
                    "true" if tbad else "false",
                )
            )
        lines.append("]")
        lines.append("")
    lines.append("///|")
    lines.append("test \"UTS 46 conformance: IdnaTestV2\" {")
    lines.append("  let strict = @idna.strict")
    lines.append("  let transitional = { ..strict, transitional: true }")
    lines.append("  let complaints : Array[String] = []")
    lines.append("  let batches : Array[Array[(String, String, Bool, String, Bool, String, Bool)]] = [")
    for number in range(len(batches)):
        lines.append("    uts46_%d," % number)
    lines.append("  ]")
    lines.append("  for batch in batches {")
    lines.append("    for (source, unicode, ubad, ascii_n, nbad, ascii_t, tbad) in batch {")
    lines.append("      let name = source[:]")
    lines.append("      let u = @idna.to_unicode(name, options=strict)")
    lines.append('      note(complaints, u.name == unicode, source, "toUnicode", u.name, unicode)')
    lines.append(
        '      note_flag(complaints, !u.errors.is_empty() == ubad, source, "toUnicode status")'
    )
    lines.append("      let n = @idna.to_ascii(name, options=strict)")
    lines.append('      note(complaints, n.name == ascii_n, source, "toASCII", n.name, ascii_n)')
    lines.append(
        '      note_flag(complaints, !n.errors.is_empty() == nbad, source, "toASCII status")'
    )
    lines.append("      let t = @idna.to_ascii(name, options=transitional)")
    lines.append(
        '      note(complaints, t.name == ascii_t, source, "toASCII transitional", t.name, ascii_t)'
    )
    lines.append(
        '      note_flag(complaints, !t.errors.is_empty() == tbad, source, "toASCII transitional status")'
    )
    lines.append("    }")
    lines.append("  }")
    lines.append("  complain(complaints)")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    runs, maps = mapping_table()
    joining = joining_table()
    open(os.path.join("src", "idna", "tables.mbt"), "w", encoding="utf-8", newline="\n").write(
        emit_tables(runs, maps, joining)
    )
    cases = idna_suite()
    open(
        os.path.join("src", "idna", "vectors_test.mbt"), "w", encoding="utf-8", newline="\n"
    ).write(emit_idna_tests(cases))
    # What is written is already laid out the way the formatter would, but only
    # `moon fmt` can promise it: the wrapped literals are its decision.
    subprocess.run(["moon", "fmt"], check=False)
    sys.stderr.write("%d runs, %d mappings, %d cases\n" % (len(runs), len(maps), len(cases)))


if __name__ == "__main__":
    main()
