#!/usr/bin/env python3
"""Generate the sort cases from web-platform-tests.

The source is `url/urlsearchparams-sort.any.js` at the pinned revision: the
official suite for `URLSearchParams.sort()`, which is what `Query::sort`
implements. The file is a JavaScript test with the cases in a literal array at
the top; this reads that array and nothing else.

Writes src/query_sort_test.mbt. Run from the repository root. Nothing here
ships with the library.
"""

import json
import os
import subprocess
import sys
import urllib.request

# The same commit gen_whatwg.py reads its vectors from, so one revision
# explains every URL vector in the repository.
REVISION = "c548cb3536e0c70cac48099560ece0f4ea1dfbea"
SOURCE = "url/urlsearchparams-sort.any.js"
URL = (
    "https://raw.githubusercontent.com/web-platform-tests/wpt/%s/%s"
    % (REVISION, SOURCE)
)
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".cache")
NAME = "urlsearchparams-sort.any.js"


def fetch():
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, NAME)
    if not os.path.exists(path):
        sys.stderr.write("fetching %s\n" % URL)
        with urllib.request.urlopen(URL) as response:
            open(path, "wb").write(response.read())
    return open(path, encoding="utf-8").read()


def strip_comments(text):
    """The source without its `//` comments, leaving strings alone."""
    out = []
    index = 0
    in_string = False
    while index < len(text):
        character = text[index]
        if in_string:
            out.append(character)
            if character == "\\":
                index += 1
                out.append(text[index])
            elif character == '"':
                in_string = False
        elif character == '"':
            in_string = True
            out.append(character)
        elif text.startswith("//", index):
            while index < len(text) and text[index] != "\n":
                index += 1
            continue
        else:
            out.append(character)
        index += 1
    return "".join(out)


def cases():
    text = strip_comments(fetch()).lstrip()
    if not text.startswith("["):
        raise SystemExit("the suite no longer opens with an array")
    depth = 0
    in_string = False
    start = 0
    for index, character in enumerate(text):
        if in_string:
            if character == "\\":
                continue
            if character == '"':
                in_string = False
        elif character == '"':
            in_string = True
        elif character == "[":
            if depth == 0:
                start = index
            depth += 1
        elif character == "]":
            depth -= 1
            if depth == 0:
                return json.loads(text[start : index + 1])
    raise SystemExit("the case array is not closed")


def literal(text):
    out = []
    for character in text:
        point = ord(character)
        if character == '"':
            out.append('\\"')
        elif character == "\\":
            out.append("\\\\")
        elif 0x20 <= point < 0x7F:
            out.append(character)
        else:
            out.append("\\u{%X}" % point)
    return '"' + "".join(out) + '"'


def emit(entries):
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by scripts/gen_query.py from web-platform-tests",
        "// url/urlsearchparams-sort.any.js, revision",
        "// c548cb3536e0c70cac48099560ece0f4ea1dfbea. Do not edit.",
        "",
        "///|",
        "/// One row of urlsearchparams-sort.any.js: a body, and the pairs the",
        "/// standard's sort leaves in it, in order.",
        "let sort_cases : Array[(String, Array[(String, String)])] = [",
    ]
    for entry in entries:
        pairs = ", ".join(
            "(%s, %s)" % (literal(name), literal(value))
            for name, value in entry["output"]
        )
        lines.append("  (%s, [%s])," % (literal(entry["input"]), pairs))
    lines.append("]")
    lines.append("")
    # The suite ends with a row about a live `searchParams` view editing the
    # URL it came from. This package has no such view — a `Query` is a copy —
    # so that row has no counterpart here.
    lines.append('test "sorting from web-platform-tests" {')
    lines.append("  let complaints : Array[String] = []")
    lines.append("  for row in sort_cases {")
    lines.append("    let source = row.0")
    lines.append("    let want = row.1")
    lines.append("    let query = @moonurl.Query::decode(@utf8.encode(source)[:])")
    lines.append("    query.sort()")
    lines.append("    let got = query.encode()")
    lines.append(
        "    let expected = @moonurl.Query::new(pairs=want).encode()"
    )
    lines.append(
        '    note(complaints, got == expected, source, "sort", got, expected)'
    )
    lines.append("  }")
    lines.append("  complain(complaints)")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    entries = cases()
    open(
        os.path.join("src", "query_sort_test.mbt"), "w", encoding="utf-8", newline="\n"
    ).write(emit(entries))
    subprocess.run(["moon", "fmt"], check=False)
    sys.stderr.write("%d sort cases\n" % len(entries))


if __name__ == "__main__":
    main()
